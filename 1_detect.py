#!/usr/bin/env python3
"""
STEP 1 - What personal information can be found automatically in a PDF?

Usage:
  python 1_detect.py input.pdf
  python 1_detect.py scan.pdf --ocr-lang nld+fra+eng
  python 1_detect.py input.pdf --spacy-model nl_core_news_md --spacy-model fr_core_news_md

Outputs (next to the PDF, or in --out-dir):
  <name>_pii_report.json      everything detected, with pages and counts
  <name>_draft_config.yaml    a config pre-filled with what was found -> edit it, then use it in step 2
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

from pii_common import (DEFAULT_REPLACEMENTS, NER_TYPES, detect_all, digital_words, fitz,
                        load_ner, ocr_words, render_page, tesseract_available, words_to_text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pdf")
    ap.add_argument("--ocr", choices=["auto", "always", "never"], default="auto",
                    help="auto = OCR only pages without a text layer (default)")
    ap.add_argument("--ocr-lang", default="nld+fra+eng", help="Tesseract languages (default nld+fra+eng)")
    ap.add_argument("--dpi", type=int, default=300)
    ap.add_argument("--spacy-model", action="append", help="spaCy model(s) for names/places; default = installed ones")
    ap.add_argument("--no-ner", action="store_true", help="regex detectors only")
    ap.add_argument("--out-dir")
    ap.add_argument("--max-per-type", type=int, default=15)
    args = ap.parse_args()

    pdf = Path(args.pdf)
    out_dir = Path(args.out_dir) if args.out_dir else pdf.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    ner = [] if args.no_ner else load_ner(args.spacy_model)
    can_ocr = tesseract_available() and args.ocr != "never"
    if args.ocr != "never" and not can_ocr:
        print("[ocr] tesseract not found: scanned pages will be skipped")

    doc = fitz.open(pdf)
    found = defaultdict(lambda: defaultdict(lambda: {"count": 0, "pages": set(), "context": ""}))
    ocr_pages = []

    for pno, page in enumerate(doc, start=1):
        words = [] if args.ocr == "always" else digital_words(page)
        if (args.ocr == "always" or len(words) < 3) and can_ocr:
            words = ocr_words(render_page(page, args.dpi), args.ocr_lang)
            ocr_pages.append(pno)
        if not words:
            print(f"[page {pno}] no text found (scan without OCR?)")
            continue
        text, _ = words_to_text(words)
        for m in detect_all(text, ner):
            key = " ".join(m.value.split())
            e = found[m.type][key]
            e["count"] += 1
            e["pages"].add(pno)
            if not e["context"]:
                a, b = max(0, m.start - 30), min(len(text), m.end + 30)
                e["context"] = " ".join(text[a:b].split())

    # ---- console report
    print(f"\n=== {pdf.name}: {len(doc)} pages, OCR used on {len(ocr_pages)} page(s) ===")
    total = 0
    for typ in sorted(found, key=lambda t: -len(found[t])):
        items = found[typ]
        print(f"\n[{typ}]  {len(items)} distinct value(s)")
        for v, e in sorted(items.items(), key=lambda kv: -kv[1]["count"])[: args.max_per_type]:
            pages = ",".join(map(str, sorted(e["pages"])))
            print(f"   {v!r:45} x{e['count']:<3} p.{pages:12} ...{e['context']}...")
        if len(items) > args.max_per_type:
            print(f"   ... and {len(items) - args.max_per_type} more (see JSON)")
        total += len(items)
    if not total:
        print("\nNothing detected.")

    # ---- JSON report
    report = {t: [{"value": v, "count": e["count"], "pages": sorted(e["pages"]), "context": e["context"]}
                  for v, e in items.items()] for t, items in found.items()}
    jpath = out_dir / f"{pdf.stem}_pii_report.json"
    jpath.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")

    # ---- draft config
    q = lambda s: json.dumps(s, ensure_ascii=False)  # JSON string == valid YAML string
    lines = [
        "# Draft generated by 1_detect.py. REVIEW IT: remove false positives, add what was missed.",
        f"ocr_lang: {q(args.ocr_lang)}",
        "case_sensitive: false",
        "style:",
        "  mode: replace      # replace = white box + replacement text | blackbox = black box",
        "",
        "# Detected by type -> every occurrence of that type is replaced.",
        "auto:",
    ]
    for t in found:
        if t not in NER_TYPES:
            lines.append(f"  {t}: {q(DEFAULT_REPLACEMENTS.get(t, '[' + t + ']'))}")
    lines += ["", "# Exact strings (most reliable). Same name -> same {n} number in the document.", "terms:"]
    for t in ("PERSON", "LOCATION", "ORG"):
        for i, v in enumerate(found.get(t, {}), start=1):
            prefix = "  " if t == "PERSON" else "  # "
            lines.append(f"{prefix}{q(v)}: {q(DEFAULT_REPLACEMENTS[t].replace('{n}', str(i)))}")
    lines += ["", "# Your own regex rules:", "regex: []", "#  - pattern: '\\bREF-\\d{6}\\b'", "#    replace: '[REF]'"]
    cpath = out_dir / f"{pdf.stem}_draft_config.yaml"
    cpath.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"\nSaved: {jpath}\nSaved: {cpath}   <- edit this, then run 2_anonymize.py")


if __name__ == "__main__":
    main()
